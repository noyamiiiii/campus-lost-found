def label_zh(name: str | None) -> str:
    """把 ImageNet 英文标签翻成中文；没有对应词条时保留原名。"""
    raw = (name or "").strip()
    if not raw:
        return ""
    return LABEL_ZH.get(raw.lower(), raw)


